use serde_json::json;
use std::collections::HashMap;
use std::fs;
use std::path::Path;
use std::time::Instant;
use table::{HANS, HANT, get};

const TITLE: &str = "宝可梦 (PokéAPI)";
const IMG_SIZE: u32 = 256;
const WEBP_QUALITY: f32 = 80.0;

fn build() {
    let t0 = Instant::now();
    let cache = Path::new("cache");
    let build = Path::new("build");
    let db = db::Db::load(&cache.join("csv"));
    let py = pinyin::Pinyin::load(cache, Path::new("data/pinyin_overrides.tsv"));
    println!("loaded data in {:.1}s", t0.elapsed().as_secs_f64());

    let official: HashMap<u32, (String, String)> = db
        .species
        .iter()
        .filter_map(|s| {
            let h = get(&db.species_name, s.id, HANS)?;
            Some((s.id, (h.to_string(), get(&db.species_name, s.id, HANT).unwrap_or(h).to_string())))
        })
        .collect();
    let (mut legacy, missing) = legacy::load(cache, &official);
    if !missing.is_empty() {
        println!("52poke: {} pages without name table, retrying with （宝可梦） suffix", missing.len());
        fetch::poke52_retry(cache, &missing);
        let (l2, still) = legacy::load(cache, &official);
        legacy = l2;
        if !still.is_empty() {
            println!("52poke: still no name table for {}: {}", still.len(), still.join(" "));
        }
    }
    println!(
        "legacy names: {} species, {} names",
        legacy.len(),
        legacy.values().map(Vec::len).sum::<usize>()
    );

    let ids: Vec<u32> = db.pokemon.iter().map(|p| p.id).collect();
    let poke_img = images::pokemon(cache, build, &ids, IMG_SIZE, WEBP_QUALITY);
    let idents: Vec<String> = db.items.iter().map(|i| i.ident.clone()).collect();
    let item_img = images::items(cache, build, &idents, WEBP_QUALITY);
    println!("images: {} pokemon, {} items ({:.1}s)", poke_img.len(), item_img.len(), t0.elapsed().as_secs_f64());

    let mut d = yomitan::Dict::default();
    render::tags(&mut d);
    let ctx = render::Ctx::new(&db, &py, poke_img, item_img, legacy);
    let counts = ctx.build(&mut d);
    let mut c: Vec<_> = counts.into_iter().collect();
    c.sort();
    println!("entries: {c:?}; term rows: {}", d.terms.len());

    // only ship images that entries reference
    let mut media: Vec<(String, std::path::PathBuf)> = ctx
        .poke_img
        .values()
        .chain(ctx.item_img.values())
        .map(|i| (i.zip_path.clone(), i.file.clone()))
        .collect();
    media.sort();
    media.dedup_by(|a, b| a.0 == b.0);
    d.media = media;

    let review = py.review.lock().unwrap();
    let mut lines = vec!["category\tterm\treading\tambiguous".to_string()];
    let mut seen = std::collections::HashSet::new();
    for (c, t, r, n) in review.iter() {
        if seen.insert(t.clone()) {
            lines.push(format!("{c}\t{t}\t{r}\t{n}"));
        }
    }
    fs::create_dir_all(build).unwrap();
    fs::write(build.join("pinyin_review.tsv"), lines.join("\n") + "\n").unwrap();
    println!("pinyin review: {} names -> build/pinyin_review.tsv", lines.len() - 1);

    let revision = std::env::var("POKEYOMI_REVISION").unwrap_or_else(|_| utc_revision());
    let mut index = json!({
        "title": TITLE,
        "revision": revision,
        "format": 3,
        "sequenced": true,
        "author": "generated by pokeyomi from PokéAPI",
        "url": "https://pokeapi.co/",
        "sourceLanguage": "zh",
        "targetLanguage": "zh",
        "description": "Pokémon species, moves, abilities, items, types and natures. Simplified, Traditional and legacy/regional headwords; Chinese, English and Japanese names; official artwork.",
        "attribution": "Data: PokéAPI (pokeapi/pokeapi, BSD-3-Clause; data originally from veekun) and PokeAPI/sprites. Pokémon names, text and artwork © Nintendo / Creatures Inc. / GAME FREAK inc. / The Pokémon Company. Legacy and regional names: 52poke 神奇宝贝百科 (CC BY-NC-SA 3.0). Readings generated with CC-CEDICT (CC BY-SA 4.0) and Unicode Unihan. Personal, non-commercial use."
    });
    // Self-updating: Yomitan fetches indexUrl, compares `revision` (dot-separated integers of
    // equal length compare numerically) and downloads downloadUrl when newer.
    if let Ok(repo) = std::env::var("POKEYOMI_REPO") {
        let base = format!("https://github.com/{repo}/releases/latest/download");
        index["isUpdatable"] = json!(true);
        index["indexUrl"] = json!(format!("{base}/{INDEX_ASSET}"));
        index["downloadUrl"] = json!(format!("{base}/{ZIP_ASSET}"));
        index["url"] = json!(format!("https://github.com/{repo}"));
    }
    let styles = fs::read_to_string("data/styles.css").expect("data/styles.css");
    let out = Path::new("dist").join(ZIP_ASSET);
    match d.write(&out, &index, &styles, &cache.join("schemas")) {
        Ok(()) => println!(
            "wrote {} rev {revision} ({:.1} MB) in {:.1}s",
            out.display(),
            fs::metadata(&out).unwrap().len() as f64 / 1e6,
            t0.elapsed().as_secs_f64()
        ),
        Err(e) => {
            eprintln!("validation failed: {e}");
            std::process::exit(1);
        }
    }
    fs::write(Path::new("dist").join(INDEX_ASSET), serde_json::to_vec_pretty(&index).unwrap()).unwrap();

    let mut notes = format!(
        "Revision `{revision}` of **{TITLE}**.\n\n| Category | Entries |\n|---|---|\n"
    );
    for (k, n) in &c {
        notes.push_str(&format!("| {k} | {n} |\n"));
    }
    notes.push_str(&format!(
        "\nHeadword rows: {}. Sources: PokeAPI data `{}`, sprites `{}`, Yomitan schemas `{}`.\n\n\
         Install: Yomitan → Settings → Dictionaries → Import from URL, or download `{ZIP_ASSET}` below. \
         Yomitan's \"Check for updates\" picks up later releases automatically.\n",
        d.terms.len(),
        &fetch::POKEAPI_SHA[..7],
        &fetch::SPRITES_SHA[..7],
        fetch::YOMITAN_TAG
    ));
    fs::write(build.join("release-notes.md"), notes).unwrap();
}

const ZIP_ASSET: &str = "pokemon-zh.zip";
const INDEX_ASSET: &str = "index.json";

/// "YYYY.M.D.HHMM" in UTC: always four integer parts, so Yomitan's compareRevisions
/// orders successive builds numerically.
fn utc_revision() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_secs() as i64;
    let (days, rem) = (secs.div_euclid(86_400), secs.rem_euclid(86_400));
    // civil-from-days (Howard Hinnant)
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = yoe + era * 400 + i64::from(m <= 2);
    format!("{y}.{m}.{d}.{:02}{:02}", rem / 3600, rem % 3600 / 60)
}

fn main() {
    let cmd = std::env::args().nth(1).unwrap_or_default();
    match cmd.as_str() {
        "fetch" => fetch::run(Path::new("cache")),
        "build" => build(),
        "all" => {
            fetch::run(Path::new("cache"));
            build();
        }
        _ => {
            eprintln!("usage: pokeyomi <fetch|build|all>   (run from the project root)");
            std::process::exit(2);
        }
    }
}
